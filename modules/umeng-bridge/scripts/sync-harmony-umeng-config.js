'use strict';

const { mkdirSync, readFileSync, writeFileSync } = require('node:fs');
const path = require('node:path');

function requireString(value, field) {
  if (typeof value !== 'string' || value.trim().length === 0) {
    throw new TypeError(`Umeng config field ${field} must be a non-empty string`);
  }
  return value;
}

function syncHarmonyUmengConfig({ configPath, harmonyDir }) {
  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const appKey = requireString(config.android?.appKey, 'android.appKey');
  const channel = requireString(config.channel, 'channel');
  const messageSecret = requireString(config.android?.messageSecret, 'android.messageSecret');

  const etsConfigPath = path.join(harmonyDir, 'entry', 'src', 'main', 'ets', 'config', 'UmengConfig.ets');
  mkdirSync(path.dirname(etsConfigPath), { recursive: true });
  writeFileSync(
    etsConfigPath,
    [
      '// Generated by yarn prebuild:harmony from config/umeng.json. Do not edit.',
      `export const UMENG_APP_KEY: string = ${JSON.stringify(appKey)};`,
      `export const UMENG_CHANNEL: string = ${JSON.stringify(channel)};`,
      `export const UMENG_MESSAGE_SECRET: string = ${JSON.stringify(messageSecret)};`,
      '',
    ].join('\n'),
    'utf8',
  );

  const rawfilePath = path.join(harmonyDir, 'AppScope', 'resources', 'rawfile', 'umconfig.json');
  mkdirSync(path.dirname(rawfilePath), { recursive: true });
  writeFileSync(rawfilePath, `${JSON.stringify({ appKey, channel }, null, 2)}\n`, 'utf8');
}

module.exports = { syncHarmonyUmengConfig };
